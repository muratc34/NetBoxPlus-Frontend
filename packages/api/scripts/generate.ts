// Generates the TypeScript types of every backend API from the OpenAPI documents in ../openapi.
// Usage: node scripts/generate.ts
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
import { services } from '../src/services.ts';
import { splitDocument, type OpenApiDocument } from './split.ts';

const root = new URL('../', import.meta.url);
const output = new URL('src/generated/', root);

const source = JSON.parse(await readFile(new URL('openapi/source.json', root), 'utf8')) as { commit: string };

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });

for (const service of services) {
  const document = JSON.parse(
    await readFile(new URL(`openapi/${service.name}.json`, root), 'utf8'),
  ) as OpenApiDocument;
  const halves = splitDocument(document, service);

  for (const [area, half] of Object.entries(halves)) {
    // Not `immutable`: openapi-fetch's Readable<T> only recognises mutable arrays, and turned every `readonly T[]`
    // in a response into an object whose array methods were not callable.
    const ast = await openapiTS(half as Parameters<typeof openapiTS>[0]);
    const header =
      `// Generated by scripts/generate.ts from ${service.name}.json (${area} paths) ` +
      `of NetBoxPlus-Backend at ${source.commit}. Do not edit.\n\n`;
    await writeFile(new URL(`${service.name}.${area}.ts`, output), header + astToString(ast));
  }
}

console.log(`Generated ${String(services.length * 2)} files from backend commit ${source.commit}.`);
